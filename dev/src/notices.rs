//! `pipelith-dev notices [--check]`: the crate table in
//! `docs/THIRD-PARTY-NOTICES.md`, from what `Cargo.lock` resolves on normal
//! dependency edges of the published crate, and the prose around it held
//! to the table (dev T18, V40). Ported from actlith-dev, itself from
//! pklith-dev; MIT, same author.

use crate::block;
use crate::facts;
use crate::io::{Doc, Failed, read, run, update};
use std::fmt::Write as _;
use std::path::Path;

const DOC: Doc = Doc {
    path: "docs/THIRD-PARTY-NOTICES.md",
    verb: "notices",
};

/// A crate the published crate ships: name, version, licence.
pub(crate) type Crate = (String, String, String);

/// The crates in `cargo tree -f '{p}|{l}' --prefix none` output, sorted
/// and once each, without the crate `own` itself.
#[must_use]
pub(crate) fn crates(tree: &str, own: &str) -> Vec<Crate> {
    let mut found: Vec<Crate> = tree
        .lines()
        .filter_map(parse)
        .filter(|c| c.0 != own)
        .collect();
    found.sort();
    found.dedup();
    found
}

/// One `name vX.Y.Z (path)|licence` line.
fn parse(line: &str) -> Option<Crate> {
    let (package, licence) = line.split_once('|')?;
    let mut words = package.split_whitespace();
    let (name, version) = (words.next()?, words.next()?.strip_prefix('v')?);
    // cargo marks a crate it already printed with `(*)`, after the licence.
    let licence = licence.trim().trim_end_matches("(*)").trim_end();
    Some((name.to_owned(), version.to_owned(), licence.to_owned()))
}

/// The table block, markers included.
#[must_use]
pub(crate) fn table(crates: &[Crate]) -> String {
    let mut out = String::from(
        "<!-- BEGIN crates: generated by `cargo run -p pipelith-dev -- notices` from Cargo.lock; do not edit -->\n| Crate | Version | Licence |\n| --- | --- | --- |\n",
    );
    for (name, version, licence) in crates {
        let _ = writeln!(out, "| {name} | {version} | {licence} |");
    }
    out.push_str("<!-- END crates -->\n");
    out
}

/// The first sentence's claim for `direct` dependencies and `total` crates.
fn claim(direct: usize, total: usize) -> String {
    let noun = if direct == 1 {
        "dependency"
    } else {
        "dependencies"
    };
    format!("**{direct} direct {noun}**, which pulls in {total} crates")
}

/// What the prose claims that the table does not bear out: the direct and
/// total counts in its first sentence, and that every crate is under MIT.
#[must_use]
pub(crate) fn stale_prose(
    doc: &str,
    direct: usize,
    crates: &[Crate],
) -> Vec<String> {
    let prose = doc.split_whitespace().collect::<Vec<_>>().join(" ");
    let (path, claim) = (DOC.path, claim(direct, crates.len()));
    let wrong_count =
        (!prose.contains(&claim)).then(|| format!("{path} must say {claim}"));
    let not_mit = crates.iter().filter(|(_, _, l)| !l.contains("MIT"));
    let wrong_licence = not_mit.map(|(n, _, l)| {
        format!("{n} is {l}, not available under MIT as {path} says")
    });
    wrong_count.into_iter().chain(wrong_licence).collect()
}

/// `cargo tree` arguments for the crate `name`, offline from the lock.
fn tree(name: &str) -> [&str; 11] {
    [
        "tree",
        "-p",
        name,
        "-e",
        "normal",
        "--prefix",
        "none",
        "-f",
        "{p}|{l}",
        "--locked",
        "--offline",
    ]
}

/// Render or check.
///
/// # Errors
///
/// Stale prose or drift (1), cargo or a file failing (2).
pub(crate) fn run_verb(repo: &Path, check: bool) -> Result<(), Failed> {
    let cargo = read(repo, "Cargo.toml")?;
    let name = facts::quoted(&cargo, "name")
        .ok_or((2, "Cargo.toml has no package name".to_owned()))?;
    let direct = facts::dependencies(&cargo).unwrap_or_default();
    let crates = crates(&run(repo, "cargo", &tree(&name))?, &name);
    let doc = read(repo, DOC.path)?;
    if let Some(stale) = stale_prose(&doc, direct, &crates).into_iter().next() {
        return Err((1, stale));
    }
    let wanted = block::splice(&doc, "crates", &table(&crates)).ok_or((
        2,
        format!("{} has no <!-- BEGIN crates --> block", DOC.path),
    ))?;
    update(repo, &DOC, &wanted, check)
}

