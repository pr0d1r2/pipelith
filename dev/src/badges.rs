///
/// No crates.io or docs.rs badge yet: the crate is unpublished until the
/// owner approves the first release (T2), and a badge for a page that does
/// not exist would be a false claim. They join here on publication. The
/// library touches no network at all (SPEC.md V1), hence `network none`.
