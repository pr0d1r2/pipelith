/// shields.io path text: `-` doubles, a space is `_`, and these encode.
fn esc(text: &str) -> String {
    text.replace('-', "--")
        .replace('%', "%25")
        .replace('+', "%2B")
        .replace('/', "%2F")
        .replace(' ', "_")
}

/// The block, markers included.
#[must_use]
pub(crate) fn render(f: &Facts) -> String {
    let values = f.cargo.values().into_iter().chain(f.gate());
    let filled = values.fold(TEMPLATE.to_owned(), |text, (name, value)| {
        text.replace(&format!("{{{name}|url}}"), &esc(&value))
            .replace(&format!("{{{name}}}"), &value)
    });
    filled.replace("{platforms}\n", &platforms(&f.platforms))
}

impl Cargo {
    /// The template's Cargo.toml facts, by name.
    fn values(&self) -> [(&'static str, String); 5] {
        [
            ("slug", self.slug.clone()),
            ("license", self.license.clone()),
            ("edition", self.edition.clone()),
            ("msrv", self.msrv.clone()),
            ("deps", self.dependencies.to_string()),
        ]
    }
}

impl Facts {
    /// The template's gate, spec and nix facts, by name.
    fn gate(&self) -> [(&'static str, String); 6] {
        let (n, (inv, bugs, nodes)) = (&self.nixpkgs, self.spec);
        let steps = format!("{} commit / {} push", self.steps.0, self.steps.1);
        [
            ("steps", steps),
            ("floor", self.floor.clone()),
            ("inv", inv.to_string()),
            ("bugs", bugs.to_string()),
            ("nodes", nodes.to_string()),
            ("nixpkgs", format!("{} ({} - {})", n.series, n.day, n.rev)),
        ]
    }
}

/// One badge per platform CI builds on, then the blank line before the
/// credits.
fn platforms(list: &[Platform]) -> String {
    let mut out: String = list
        .iter()
        .map(|(arch, os)| {
            format!(
                "[![{arch} {os}](https://img.shields.io/badge/{os}-5277C3?logo={arch}&logoColor=white)](.github/workflows/ci.yml)\n"
            )
        })
        .collect();
    out.push('\n');
    out
}

/// The disclaimer's quoted numbers that no longer match the facts. Its
/// lines wrap, so the text is joined before matching. Unlike pklith's, it
/// quotes no step counts: `pklith lay` adds steps one commit at a time,
/// and prose no fixer can rewrite would refuse each of those commits; the
/// badge carries the count instead.
#[must_use]
pub(crate) fn stale_prose(disclaimer: &str, f: &Facts) -> Vec<String> {
    let prose = disclaimer.split_whitespace().collect::<Vec<_>>().join(" ");
    let (inv, bugs, _) = f.spec;
    [
        format!("**{inv} invariants**"),
        format!("**{bugs} bugs**"),
        format!("floor of {}%", f.floor),
    ]
    .into_iter()
    .filter(|want| !prose.contains(want.as_str()))
    .collect()
}

