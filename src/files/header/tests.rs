//! `header`: the bytes every generated `#`-comment file starts with (V27).

use super::header;

#[test]
fn matches_actlith_bytes_for_actlith() {
    let want = "# generated by actlith gen from .actlith; do not edit\n";
    assert_eq!(header("actlith", ".actlith"), want);
}

#[test]
fn names_the_tool_and_its_config() {
    let want = "# generated by lablith gen from .lablith; do not edit\n";
    assert_eq!(header("lablith", ".lablith"), want);
}

#[test]
fn is_one_comment_line() {
    let line = header("tool", "cfg");
    assert!(line.starts_with("# "), "{line:?}");
    assert_eq!(line.lines().count(), 1, "{line:?}");
    assert!(line.ends_with('\n'), "{line:?}");
}
